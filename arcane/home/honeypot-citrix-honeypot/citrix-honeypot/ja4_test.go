// TestPeekJA4KnownVectorNoSigAlgs reuses ja3_test.go's own known-vector
// ClientHello record (version 0x0303, ciphers 4865/4866/4867/49195/49199,
// extensions 0/23/65281/10/11/16, ALPN "h2", no signature_algorithms or
// supported_versions extension) -- the expected JA4 was computed
// independently by re-deriving FoxIO's reference algorithm (python/ja4.py +
// python/common.py's to_ja4/get_hex_sorted/sha_encode, byte for byte) in a
// standalone Python script, not derived from this Go code.
//
// t12 (TLS 1.2, no supported_versions override) d (SNI present)
// 05 (5 ciphers) 06 (6 extensions, SNI+ALPN included in the count) h2 (ALPN)
// _ cipher hash of sorted 1301,1302,1303,c02b,c02f
// _ extension hash of sorted 000a,000b,0017,ff01 (0000/0010 excluded, no
// signature_algorithms extension so nothing appended).
func TestPeekJA4KnownVectorNoSigAlgs(t *testing.T) {
	record := []byte{
		0x16, 0x03, 0x01, 0x00, 0x64, 0x01, 0x00, 0x00, 0x60, 0x03, 0x03,
		0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
		0x00, 0x0a, 0x13, 0x01, 0x13, 0x02, 0x13, 0x03, 0xc0, 0x2b, 0xc0,
		0x2f, 0x01, 0x00, 0x00, 0x2d, 0x00, 0x00, 0x00, 0x05, 0x00, 0x03,
		0x00, 0x00, 0x00, 0x00, 0x17, 0x00, 0x00, 0xff, 0x01, 0x00, 0x01,
		0x00, 0x00, 0x0a, 0x00, 0x08, 0x00, 0x06, 0x00, 0x1d, 0x00, 0x17,
		0x00, 0x18, 0x00, 0x0b, 0x00, 0x02, 0x01, 0x00, 0x00, 0x10, 0x00,
		0x05, 0x00, 0x03, 0x02, 0x68, 0x32,
	}
	const want = "t12d0506h2_e133e205ac38_368bf2d64253"

	got := peekJA4(bufio.NewReader(bytes.NewReader(record)))
	if got != want {
		t.Fatalf("peekJA4 = %q, want %q", got, want)
	}
}

// TestPeekJA4KnownVectorWithSigAlgsAndGREASE exercises the rest of the
// algorithm the vector above doesn't reach: a #002b supported_versions
// override (client_version 0x0303 legacy, real version 0x0304 via the
// extension, GREASE 0x2a2a mixed in and filtered), a GREASE cipher
// (0x0a0a) filtered from both the count and the hash, a
// signature_algorithms extension (0x0403, 0x0804, GREASE 0x0a0a filtered)
// appended unsorted after the sorted+SNI/ALPN-excluded extension hash, and
// an 8-byte ALPN value ("http/1.1") truncated to its first+last character.
// Expected JA4 again computed independently via the same standalone
// re-derivation of FoxIO's reference algorithm, from the same raw bytes.
func TestPeekJA4KnownVectorWithSigAlgsAndGREASE(t *testing.T) {
	record := []byte{
		0x16, 0x03, 0x01, 0x00, 0x6b, 0x01, 0x00, 0x00, 0x67, 0x03, 0x03,
		0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
		0x00, 0x06, 0x13, 0x01, 0x13, 0x02, 0x0a, 0x0a, 0x01, 0x00, 0x00,
		0x38, 0x00, 0x00, 0x00, 0x10, 0x00, 0x0e, 0x00, 0x00, 0x0b, 0x65,
		0x78, 0x61, 0x6d, 0x70, 0x6c, 0x65, 0x2e, 0x63, 0x6f, 0x6d, 0x00,
		0x2b, 0x00, 0x05, 0x04, 0x03, 0x04, 0x2a, 0x2a, 0x00, 0x0d, 0x00,
		0x08, 0x00, 0x06, 0x04, 0x03, 0x08, 0x04, 0x0a, 0x0a, 0x00, 0x10,
		0x00, 0x0b, 0x00, 0x09, 0x08, 0x68, 0x74, 0x74, 0x70, 0x2f, 0x31,
		0x2e, 0x31,
	}
	const want = "t13d0204h1_62ed6f6ca7ad_ef5f37ab036a"

	got := peekJA4(bufio.NewReader(bytes.NewReader(record)))
	if got != want {
		t.Fatalf("peekJA4 = %q, want %q", got, want)
	}
}
